/**
 * Format a raw digits-only phone number according to country standard patterns.
 */
export function formatPhoneNumberByCountry(num: string, country: Country): string {
  if (!num) return '';
  const code = country.code;

  // India: 5 5 (e.g. 98765 43210)
  if (code === 'IN') {
    if (num.length > 5) {
      return `${num.slice(0, 5)} ${num.slice(5)}`;
    }
    return num;
  }

  // NANP countries (US, CA, and Caribbean +1): 3 3 4 (e.g. 202 555 0199)
  if (country.dialCode === '+1') {
    if (num.length > 6) {
      return `${num.slice(0, 3)} ${num.slice(3, 6)} ${num.slice(6)}`;
    } else if (num.length > 3) {
      return `${num.slice(0, 3)} ${num.slice(3)}`;
    }
    return num;
  }

  // UK, Bangladesh: 4 6 (e.g. 7911 123456)
  if (code === 'GB' || code === 'BD') {
    if (num.length > 4) {
      return `${num.slice(0, 4)} ${num.slice(4)}`;
    }
    return num;
  }

  // 8-digit countries (Singapore, Qatar, Kuwait, Bahrain, Oman, Hong Kong, etc.): 4 4
  if (country.maxLength === 8) {
    if (num.length > 4) {
      return `${num.slice(0, 4)} ${num.slice(4)}`;
    }
    return num;
  }

  // 7-digit countries: 3 4
  if (country.maxLength === 7) {
    if (num.length > 3) {
      return `${num.slice(0, 3)} ${num.slice(3)}`;
    }
    return num;
  }

  // 6-digit countries: 3 3
  if (country.maxLength === 6) {
    if (num.length > 3) {
      return `${num.slice(0, 3)} ${num.slice(3)}`;
    }
    return num;
  }

  // Australia: 3 3 3 (e.g. 412 345 678)
  if (code === 'AU') {
    if (num.length > 6) {
      return `${num.slice(0, 3)} ${num.slice(3, 6)} ${num.slice(6)}`;
    } else if (num.length > 3) {
      return `${num.slice(0, 3)} ${num.slice(3)}`;
    }
    return num;
  }

  // France: 1 2 2 2 2 (e.g. 6 12 34 56 78)
  if (code === 'FR') {
    if (num.length > 7) {
      return `${num.slice(0, 1)} ${num.slice(1, 3)} ${num.slice(3, 5)} ${num.slice(5, 7)} ${num.slice(7)}`;
    } else if (num.length > 5) {
      return `${num.slice(0, 1)} ${num.slice(1, 3)} ${num.slice(3, 5)} ${num.slice(5)}`;
    } else if (num.length > 3) {
      return `${num.slice(0, 1)} ${num.slice(1, 3)} ${num.slice(3)}`;
    } else if (num.length > 1) {
      return `${num.slice(0, 1)} ${num.slice(1)}`;
    }
    return num;
  }

  // Spain, Switzerland, Sweden: 3 2 2 2
  if (code === 'ES' || code === 'CH' || code === 'SE') {
    if (num.length > 7) {
      return `${num.slice(0, 3)} ${num.slice(3, 5)} ${num.slice(5, 7)} ${num.slice(7)}`;
    } else if (num.length > 5) {
      return `${num.slice(0, 3)} ${num.slice(3, 5)} ${num.slice(5)}`;
    } else if (num.length > 3) {
      return `${num.slice(0, 3)} ${num.slice(3)}`;
    }
    return num;
  }

  // Japan, South Korea, Mexico: 2 4 4 (e.g. 90 1234 5678)
  if (code === 'JP' || code === 'KR' || code === 'MX') {
    if (num.length > 6) {
      return `${num.slice(0, 2)} ${num.slice(2, 6)} ${num.slice(6)}`;
    } else if (num.length > 2) {
      return `${num.slice(0, 2)} ${num.slice(2)}`;
    }
    return num;
  }

  // Brazil: 2 5 4 (e.g. 11 91234 5678)
  if (code === 'BR') {
    if (num.length > 7) {
      return `${num.slice(0, 2)} ${num.slice(2, 7)} ${num.slice(7)}`;
    } else if (num.length > 2) {
      return `${num.slice(0, 2)} ${num.slice(2)}`;
    }
    return num;
  }

  // 9-digit countries (UAE, Saudi Arabia, South Africa, Sri Lanka, Ireland, New Zealand, etc.): 2 3 4
  if (country.maxLength === 9) {
    if (num.length > 5) {
      return `${num.slice(0, 2)} ${num.slice(2, 5)} ${num.slice(5)}`;
    } else if (num.length > 2) {
      return `${num.slice(0, 2)} ${num.slice(2)}`;
    }
    return num;
  }

  // 10-digit countries (Italy, Turkey, Nigeria, Philippines, Pakistan, etc.): 3 3 4
  if (country.maxLength === 10) {
    if (num.length > 6) {
      return `${num.slice(0, 3)} ${num.slice(3, 6)} ${num.slice(6)}`;
    } else if (num.length > 3) {
      return `${num.slice(0, 3)} ${num.slice(3)}`;
    }
    return num;
  }

  // 11-12 digit countries (Germany, China, Indonesia): 3 4 4
  if (country.maxLength >= 11) {
    if (num.length > 7) {
      return `${num.slice(0, 3)} ${num.slice(3, 7)} ${num.slice(7)}`;
    } else if (num.length > 3) {
      return `${num.slice(0, 3)} ${num.slice(3)}`;
    }
    return num;
  }

  // Generic fallback: 3 3 4 or 3 4
  if (num.length > 6) {
    return `${num.slice(0, 3)} ${num.slice(3, 6)} ${num.slice(6)}`;
  } else if (num.length > 3) {
    return `${num.slice(0, 3)} ${num.slice(3)}`;
  }
  return num;
}
